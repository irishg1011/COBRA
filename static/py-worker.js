// ---------------- load ----------------
function load(indexURL) {
    if (!loading) {
        loading = (async () => {
            importScripts(indexURL + "pyodide.js");
            pyodide = await loadPyodide({ indexURL });
            await pyodide.runPythonAsync(GUARD_SETUP);
            return pyodide;
        })();
        loading.catch(() => { loading = null; });
    }
    return loading;
}

// ---------------- input() ----------------
// The page shows its inline field and answers with {type: "input"}. In the
// collected / grade modes the wait is taken off the time limit here; block
// mode's own program does that itself.
function askInput(promptText) {
    const run = current;
    if (!run) return Promise.resolve(null);
    const guard = run.mode !== "block" ? pyodide.globals.get("_cobrabyte_guard") : null;
    if (guard) guard.pause();
    return new Promise((resolve) => {
        pendingInputs[run.id] = (value) => {
            if (guard) { guard.resume(); guard.destroy(); }
            resolve(value);
        };
        self.postMessage({ type: "input", id: run.id, prompt: String(promptText == null ? "" : promptText) });
    });
}
// The names the moved programs call through `import js as _cobrabyte_js`.
self.cobraByteTerminalInput = askInput;
self.cobraByteSandboxInput = askInput;
self.cobraByteAdminSandboxInput = askInput;

function syncModuleFilesToFS(files) {
    try { pyodide.FS.mkdirTree("/lesson_modules"); } catch (err) { /* already exists */ }
    (files || []).forEach(({ filename, code }) => {
        const name = (filename || "").trim();
        if (!name.toLowerCase().endsWith(".py")) return;
        const baseName = name.split("/").pop().split("\\").pop();
        try {
            pyodide.FS.writeFile(`/lesson_modules/${baseName}`, code || "", { encoding: "utf8" });
        } catch (err) { /* ignore */ }
    });
}

// ---------------- run ----------------
async function run(msg) {
    const { id, mode } = msg;
    try {
        await load(msg.indexURL);
    } catch (err) {
        self.postMessage({ type: "loadError", message: String(err && err.message || err) });
        self.postMessage({ type: "done", id, ok: false, loadFailed: true, message: String(err && err.message || err) });
        return;
    }
    current = { id, mode };
    const post = (text) => self.postMessage({ type: "output", id, text: String(text) });
    try {
        if (msg.files && msg.files.length) syncModuleFilesToFS(msg.files);
        const g = pyodide.globals;
        let program = PROGRAMS[mode];
        if (!program) throw new Error("Unknown run mode: " + mode);
        if (mode === "block") {
            program = program.replace("_COBRABYTE_MAX_SECONDS = __MAX_SECONDS__", "_COBRABYTE_MAX_SECONDS = " + Number(msg.maxSeconds || 5));
            g.set("_cobrabyte_user_code", msg.code || "");
            g.set("_cobrabyte_module_files", msg.moduleFiles || []);
            g.set("_cobrabyte_write", post);
            g.set("_cobrabyte_read_input", askInput);
        } else {
            g.get("_cobrabyte_new_guard")(msg.maxLines || 1000, msg.maxSeconds || 5);
            g.set("_cobrabyte_live", msg.live ? post : null);
            if (mode === "grade") {
                g.set("_cobrabyte_grade_code", msg.code || "");
                g.set("_cobrabyte_grade_inputs", msg.givenInputs || []);
            } else {
                g.set("_cobrabyte_user_code", msg.code || "");
            }
        }
        self.postMessage({ type: "started", id });
        const result = await pyodide.runPythonAsync(program);
        self.postMessage({ type: "done", id, ok: true, result: result == null ? null : String(result) });
    } catch (err) {
        self.postMessage({ type: "done", id, ok: false, message: err && err.message ? err.message : String(err) });
    } finally {
        if (current && current.id === id) current = null;
        delete pendingInputs[id];
    }
}

self.onmessage = (e) => {
    const msg = e.data || {};
    if (msg.type === "load") {
        load(msg.indexURL).then(
            () => self.postMessage({ type: "ready" }),
            (err) => self.postMessage({ type: "loadError", message: String(err && err.message || err) })
        );
    } else if (msg.type === "run") {
        run(msg);
    } else if (msg.type === "input") {
        const resolve = pendingInputs[msg.id];
        if (resolve) { delete pendingInputs[msg.id]; resolve(msg.value == null ? null : String(msg.value)); }
    }
};
